"""Write `crates/ax-config/src/constants.rs`: the fixed numbers and names of Python's `config.py`, so the two cannot drift apart.

    python tools/parity/gen_config_constants.py          # rewrite the file
    python tools/parity/gen_config_constants.py --check  # fail if it is out of date

Every module-level UPPER_CASE integer, float, bool and string of `config.py` is written out, read with a clean environment (no
`ARCHIVE_X_*` / `TELEGRAM_ARCHIVE_*` variable) so the values are the defaults. The ones that come from an environment variable (host, ports,
the metadata cache lifetime, the Telegram connect timeout) and the version are not constants; `ax-config::settings` reads them the way Python does.
Paths are not written either; `ax-config::layout` builds them from the data folder.
"""
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "ax-config" / "src" / "constants.rs"
ENV_DRIVEN = {"HOST", "PORT", "LOCAL_PLAYER_PORT", "LOCAL_PLAYER_HOST", "METADATA_CACHE_TTL_SECONDS", "TELEGRAM_BACKGROUND_CONNECT_TIMEOUT_SECONDS", "APP_VERSION", "APP_COMMIT"}
# Already ported and checked against Python by their own tests.
ALREADY_PORTED = {"EXECUTION_LANE_CAPACITIES"}


def rust_str(value: str) -> str:
    assert value.isascii() and '"' not in value and "\\" not in value, value
    return f'"{value}"'


def render() -> str:
    tmp = tempfile.mkdtemp(prefix="axcfg-")
    for k in list(os.environ):
        if k.startswith(("ARCHIVE_X_", "TELEGRAM_ARCHIVE_")):
            del os.environ[k]
    os.environ["ARCHIVE_X_DATA_DIR"] = tmp
    sys.path.insert(0, str(ROOT))
    from telegram_archive import config

    lines = [
        "// @generated by tools/parity/gen_config_constants.py from telegram_archive/config.py. Do not edit: CI regenerates it and fails on a difference.",
        "#![allow(clippy::unreadable_literal, clippy::excessive_precision)]",
        "",
    ]
    for name, value in vars(config).items():
        if not name.isupper() or name.startswith("_") or name in ENV_DRIVEN or name in ALREADY_PORTED:
            continue
        if isinstance(value, bool):
            lines.append(f"pub const {name}: bool = {'true' if value else 'false'};")
        elif isinstance(value, int):
            lines.append(f"pub const {name}: i64 = {value};")
        elif isinstance(value, float):
            text = repr(value)
            assert text not in ("inf", "nan"), name
            lines.append(f"pub const {name}: f64 = {text if any(c in text for c in '.e') else text + '.0'};")
        elif isinstance(value, str):
            lines.append(f"pub const {name}: &str = {rust_str(value)};")
        elif isinstance(value, frozenset):
            items = sorted(value)
            lines.append(f"pub const {name}: [&str; {len(items)}] = [")
            lines += [f"    {rust_str(i)}," for i in items]
            lines.append("];")
        elif isinstance(value, dict) and all(isinstance(k, str) and isinstance(v, str) for k, v in value.items()):
            lines.append(f"pub const {name}: [(&str, &str); {len(value)}] = [")
            lines += [f"    ({rust_str(k)}, {rust_str(v)})," for k, v in value.items()]
            lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run python tools/parity/gen_config_constants.py")
            sys.exit(1)
        print("config constants are up to date")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
