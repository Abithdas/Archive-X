"""Write the SQL that creates a fresh Archive X database (the Python backend's own result), for the Rust side to run.

    python tools/parity/dump_schema_sql.py            # rewrite crates/ax-db/schema/schema.sql
    python tools/parity/dump_schema_sql.py --check    # exit 1 if the committed file is out of date

The file holds every table, index, trigger and view of a database the Python code just created (in creation order, without the tables the
full-text indexes make for themselves), then the rows such a database starts with (the settings and data counters, written as OR REPLACE because the triggers on `settings` count into `data_versions` while they are inserted; not the log line).
`crates/ax-db/src/schema.rs` runs it, and a test compares the result with schema.json.
"""
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "crates" / "ax-db" / "schema" / "schema.sql"

HEADER = "-- Generated by tools/parity/dump_schema_sql.py from a database the Python backend created. Do not edit by hand.\n"


def sql_literal(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return repr(v)
    return "'" + str(v).replace("'", "''") + "'"


def build() -> str:
    from telegram_archive.core.auth import SessionStore
    from telegram_archive.core.database import Database
    with tempfile.TemporaryDirectory() as d:
        db = Database(Path(d) / "schema.db")
        SessionStore(db)
        with db.lock:
            objects = db.conn.execute("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL ORDER BY rowid").fetchall()
            virtual = [name for kind, name, sql in objects if kind == "table" and sql.upper().startswith("CREATE VIRTUAL TABLE")]
            shadows = tuple(f"{v}_" for v in virtual)
            statements = []
            for kind, name, sql in objects:
                if kind == "table" and name.startswith(shadows) and not sql.upper().startswith("CREATE VIRTUAL TABLE"):
                    continue  # made by CREATE VIRTUAL TABLE itself
                if name.startswith("sqlite_"):
                    continue
                statements.append(sql.strip() + ";")
            seeds = []
            for table, columns in (("settings", "key, value"), ("data_versions", "scope, version")):
                for row in db.conn.execute(f"SELECT {columns} FROM {table} ORDER BY 1").fetchall():
                    seeds.append(f"INSERT OR REPLACE INTO {table}({columns}) VALUES({', '.join(sql_literal(x) for x in row)});")
    return HEADER + "\n\n".join(statements) + "\n\n-- the rows a new database starts with\n" + "\n".join(seeds) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("schema.sql is out of date: run python tools/parity/dump_schema_sql.py and review the diff (the Rust side creates new databases from it)")
            return 1
        print("schema.sql is current")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text) // 1024} KiB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
