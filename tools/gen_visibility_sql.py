"""Write crates/ax-db/src/visibility.sql from telegram_archive/core/content_mode.py (the Rust side runs the same views).

    python tools/gen_visibility_sql.py          # rewrite the file
    python tools/gen_visibility_sql.py --check  # exit 1 when it is out of date (the test suite does this)
"""
import os
import sys
import tempfile
from pathlib import Path

root = Path(__file__).resolve().parents[1]
os.environ.setdefault("ARCHIVE_X_DATA_DIR", tempfile.mkdtemp(prefix="axvis_"))
sys.path.insert(0, str(root))
from telegram_archive.core.content_mode import VISIBILITY_SQL  # noqa: E402

target = root / "crates" / "ax-db" / "src" / "visibility.sql"
text = "-- Generated by tools/gen_visibility_sql.py from telegram_archive/core/content_mode.py. Do not edit by hand.\n" + VISIBILITY_SQL + "\n"
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text(encoding="utf-8") == text else 1)
target.write_text(text, encoding="utf-8")
print("wrote", target)
